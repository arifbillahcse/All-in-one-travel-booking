/*
 * Builds public/assets/js/i18n/bn.js: the Bangla messages that the browser scripts use.
 * It collects every t("...") / T("...") string in public/assets/js and looks it up in lang/bn.json.
 *
 *   node tools/build-js-messages.cjs
 *
 * Strings built at runtime (names from <select> values) are listed in EXTRA.
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const jsDir = path.join(root, 'public', 'assets', 'js');
const dictionary = JSON.parse(fs.readFileSync(path.join(root, 'lang', 'bn.json'), 'utf8'));

const EXTRA = [
  "Cox's Bazar", 'Sundarbans', 'Sylhet', 'Bandarban', "Saint Martin's Island", 'Kuakata',
  'Weekend Escape', 'Explorer', 'Grand Bangladesh', 'Not sure yet', 'Family', 'Couple', 'Friends', 'Solo',
];

const files = fs.readdirSync(jsDir).filter((f) => f.endsWith('.js') && f !== 'bn.js').map((f) => path.join(jsDir, f));
const keys = new Set(EXTRA);
const call = /\b[tT]\(\s*("(?:[^"\\]|\\.)*"|'(?:[^'\\]|\\.)*')/g;

for (const file of files) {
  for (const [, literal] of fs.readFileSync(file, 'utf8').matchAll(call)) {
    keys.add(literal[0] === '"' ? JSON.parse(literal) : literal.slice(1, -1).replace(/\\'/g, "'"));
  }
}

const out = {};
const missing = [];
[...keys].sort().forEach((k) => (k in dictionary ? (out[k] = dictionary[k]) : missing.push(k)));

fs.writeFileSync(
  path.join(jsDir, 'i18n', 'bn.js'),
  '/* Bangla messages for the browser scripts (form errors, estimate, lightbox). Generated by tools/build-js-messages.cjs from lang/bn.json. */\n' +
    'window.TRAVELORIO_I18N = window.TRAVELORIO_I18N || {};\n' +
    'window.TRAVELORIO_I18N.bn = ' + JSON.stringify(out, null, 1) + ';\n'
);
console.log(Object.keys(out).length + ' messages written' + (missing.length ? '; MISSING in lang/bn.json: ' + JSON.stringify(missing) : ''));
